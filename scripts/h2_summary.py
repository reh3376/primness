#!/usr/bin/env python3
"""H2: the GPU against the 18 CPU cores on the bucket sieve and on 96-bit Montgomery
multiplication (docs/h2_falsifiable_prediction.md).

    scripts/h2_summary.py [--out data/results/h2_kernels]

Reads data/results/h2/{cpu,gpu}.csv (kernel,device,run,seconds,ops,ops_per_s,check;
run 0 is the warm-up), the lane results data/dumps/h2/{cpu,gpu}_lanes.bin and lanes.bin,
the hardware traces data/hardware/h2-{cpu,gpu}.jsonl when present, and H1's cost and
time shares (data/results/h1_cost.{md,csv}). Writes <out>.md and <out>.csv. Standard
library only.
"""
import csv
import json
import math
import re
import sys
from pathlib import Path

LIMIT = 10.0
H1_HOURS_FALLBACK = 3896.0


def load(path):
    rows = {}
    with open(path) as fh:
        for r in csv.reader(fh):
            if not r or r[0].startswith("#"):
                continue
            kernel, device, run, secs, ops, _, check = r
            if int(run) == 0:
                continue
            rows.setdefault(kernel, []).append((float(secs), int(ops), check))
    return rows


def median(xs):
    xs = sorted(xs)
    return xs[len(xs) // 2]


def hw(name):
    p = Path(f"data/hardware/{name}.jsonl")
    if not p.exists():
        return {}
    for line in reversed(p.read_text().splitlines()):
        r = json.loads(line)
        if r.get("kind") == "finish":
            return r["summary"]
    return {}


def lanes_check():
    d = Path("data/dumps/h2")
    try:
        a, b, lanes = (d / "cpu_lanes.bin").read_bytes(), (d / "gpu_lanes.bin").read_bytes(), (d / "lanes.bin").read_bytes()
    except FileNotFoundError:
        return None
    n = min(len(a), len(b)) // 16
    differ = sum(1 for i in range(n) if a[16 * i:16 * i + 16] != b[16 * i:16 * i + 16])
    big = 0
    for i in range(0, n, max(1, n // 64)):
        o = 112 * i
        N = int.from_bytes(lanes[o:o + 16], "little")
        x0 = int.from_bytes(lanes[o + 16:o + 32], "little")
        y = int.from_bytes(lanes[o + 32:o + 48], "little")
        if x0 * pow(y, 1 << 16, N) % N != int.from_bytes(b[16 * i:16 * i + 16], "little"):
            big += 1
    return n, differ, big


def h1():
    hours = H1_HOURS_FALLBACK
    p = Path("data/results/h1_cost.md")
    if p.exists():
        m = re.search(r"\*\*([\d,]+) laptop-hours\*\*", p.read_text())
        if m:
            hours = float(m.group(1).replace(",", ""))
    shares = {"sieving": [], "cofactorization": [], "other": []}
    p = Path("data/results/h1_cost.csv")
    if p.exists():
        with open(p) as fh:
            for r in csv.DictReader(fh):
                s, c = float(r["share_sieving"]), float(r["share_cofactorization"])
                shares["sieving"].append(s)
                shares["cofactorization"].append(c)
                shares["other"].append(1 - s - c)
    mean = {k: (sum(v) / len(v) if v else math.nan) for k, v in shares.items()}
    return hours, mean


def main(argv):
    out = argv[2] if len(argv) > 2 and argv[1] == "--out" else "data/results/h2_kernels"
    cpu, gpu = load("data/results/h2/cpu.csv"), load("data/results/h2/gpu.csv")
    rows, med = [], {}
    for dev, data in (("cpu", cpu), ("gpu", gpu)):
        for k, runs in data.items():
            secs = median([s for s, _, _ in runs])
            ops = runs[0][1]
            checks = {c for _, _, c in runs}
            med[(k, dev)] = (secs, ops, ops / secs, checks)
            rows.append(dict(kernel=k, device=dev, runs=len(runs), median_seconds=secs, ops=ops, ops_per_s=ops / secs,
                             check=";".join(sorted(checks))))
    ratio = {k: med[(k, "gpu")][2] / med[(k, "cpu")][2] for k in ("sieve", "sieve-fill", "sieve-apply", "mulmod", "copy")}
    same_sieve = med[("sieve", "cpu")][3] == med[("sieve", "gpu")][3] and len(med[("sieve", "cpu")][3]) == 1
    lc = lanes_check()
    hours, share = h1()
    X = max(ratio["sieve"], ratio["mulmod"])
    verdict = "holds" if ratio["sieve"] <= LIMIT and ratio["mulmod"] <= LIMIT else "rejected"
    bound = hours / (1 + X)
    s, c, o = share["sieving"], share["cofactorization"], share["other"]
    est_rest_cpu = hours * (s / (1 + ratio["sieve"]) + c / (1 + ratio["mulmod"]) + o)
    est_all = hours * ((s + o) / (1 + ratio["sieve"]) + c / (1 + ratio["mulmod"]))
    for r in rows:
        r.update(ratio_gpu_over_cpu=ratio.get(r["kernel"], ""))
    with open(out + ".csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        for r in rows:
            w.writerow({k: (f"{v:.6g}" if isinstance(v, float) else v) for k, v in r.items()})

    hc, hg = hw("h2-cpu"), hw("h2-gpu")
    def g(h, k, f="mean"):
        v = (h.get(k) or {}).get(f)
        return "n/a" if v is None else f"{v:.1f}"
    md = ["# H2: the GPU against the 18 CPU cores\n",
          "Generated by `scripts/h2_summary.py` from `scripts/h2_run.sh`. The prediction and criterion are"
          " `docs/h2_falsifiable_prediction.md`. Medians of five timed runs after one warm-up.\n",
          "| kernel | CPU (18 threads) | GPU (40 cores) | GPU / CPU |",
          "|---|---:|---:|---:|"]
    names = {"sieve": "bucket sieve, fill and apply (updates/s)", "sieve-fill": "  fill only", "sieve-apply": "  apply only",
             "mulmod": "Montgomery multiplication mod 96-bit n (per s)", "copy": "copy (bytes/s, read and write)"}
    for k in ("sieve", "sieve-fill", "sieve-apply", "mulmod", "copy"):
        md.append(f"| {names[k]} | {med[(k, 'cpu')][2]:.3e} | {med[(k, 'gpu')][2]:.3e} | {ratio[k]:.1f} |")
    md.append("\n**Same work on both sides.**")
    md.append(f"- Sieve: {med[('sieve', 'cpu')][1]:,} updates per run on both; the checksum (sum over the 2^29 positions of the"
              f" byte mod 256) is {'identical on every run' if same_sieve else 'NOT identical'}"
              f" ({', '.join(sorted(med[('sieve', 'cpu')][3]))}).")
    if lc:
        n, differ, big = lc
        md.append(f"- Multiplication: x0 · y^65536 mod n for {n:,} lanes computed on both sides; {differ} differ."
                  f" A sample of the GPU's lanes against Python's integers: {big} wrong.")
    md.append(f"\n**H2 {verdict}.** The ratio is {ratio['sieve']:.1f} for the sieve and {ratio['mulmod']:.1f} for the"
              f" multiplication, against a limit of {LIMIT:.0f} on each.")
    md.append(f"\nThe pre-registered bound with the larger ratio X = {X:.1f}: the relations of a 200-digit number need at least"
              f" {hours:,.0f} / (1 + {X:.1f}) = **{bound:,.0f} laptop-hours** with the GPU, if both kernels were ported perfectly"
              f" and the GPU and the CPU worked at once.")
    md.append("\nEstimates beside the verdict, with H1's mean time shares (sieving"
              f" {100 * s:.0f}%, cofactorization {100 * c:.0f}%, other {100 * o:.0f}%), each kernel sped up by its own ratio:")
    md.append(f"- the rest of `las` left on the CPU: {est_rest_cpu:,.0f} laptop-hours;")
    md.append(f"- the rest sped up like the sieve: {est_all:,.0f} laptop-hours.")
    md.append(f"\nHardware during the runs: CPU side mean power {g(hc, 'power_all_w')} W, max CPU {g(hc, 'cpu_temp_c', 'max')} °C;"
              f" GPU side mean power {g(hg, 'power_all_w')} W, max GPU {g(hg, 'gpu_temp_c', 'max')} °C, mean GPU activity"
              f" {g(hg, 'gpu_active_ratio')}.")
    Path(out + ".md").write_text("\n".join(md) + "\n")
    print(f"sieve {ratio['sieve']:.1f}x, mulmod {ratio['mulmod']:.1f}x, copy {ratio['copy']:.2f}x; H2 {verdict};"
          f" bound {bound:,.0f} h; estimates {est_rest_cpu:,.0f} and {est_all:,.0f} h")
    print(f"wrote {out}.md and {out}.csv")


if __name__ == "__main__":
    main(sys.argv)
